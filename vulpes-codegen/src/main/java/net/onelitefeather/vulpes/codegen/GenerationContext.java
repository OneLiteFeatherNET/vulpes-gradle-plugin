package net.onelitefeather.vulpes.codegen;

import com.palantir.javapoet.ClassName;

/**
 * What the generators need to know about one content release.
 *
 * @param packageName the package of the generated classes
 * @param project     the content project name, for example {@code cygnus}
 * @param version     the version of the content release
 * @param namespace   the namespace of the content, entries of this namespace get short constant names
 */
record GenerationContext(String packageName, String project, String version, String namespace) {

    /**
     * Class name prefix of the project, for example {@code Cygnus}.
     */
    String prefix() {
        return JavaNames.typeName(project);
    }

    /**
     * Class name of a generated class of this project, for example {@code className("Items")}.
     */
    ClassName className(String suffix) {
        return ClassName.get(packageName, prefix() + suffix);
    }

    /**
     * The sentence every generated class carries in its Javadoc. It has no timestamp, so equal input stays equal.
     */
    String provenance() {
        return "Generated by the Vulpes Gradle plugin from {@code " + project + "} " + version + ", do not edit.";
    }
}
