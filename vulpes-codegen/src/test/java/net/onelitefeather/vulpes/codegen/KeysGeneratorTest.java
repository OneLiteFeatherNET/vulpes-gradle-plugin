package net.onelitefeather.vulpes.codegen;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import org.junit.jupiter.api.Test;

final class KeysGeneratorTest {

    @Test
    void namesClassAfterProjectAndTypeInTheProjectPackage() {
        GeneratedSource source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS,
                List.of(new EntryKeys("cygnus:iron_sword", List.of())));

        assertEquals("CygnusItemKeys", source.className(), "class name");
        assertEquals(TestContents.PACKAGE, source.packageName(), "package");
    }

    @Test
    void declaresKeyConstantPerEntry() {
        String source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS,
                List.of(new EntryKeys("cygnus:iron_sword", List.of()))).source();

        assertTrue(source.contains("public static final Key IRON_SWORD = Key.key(\"cygnus\", \"iron_sword\");"),
                "key constant of the entry:\n" + source);
    }

    @Test
    void declaresKeysOfOtherNamespacesWithTheirNamespace() {
        String source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS,
                List.of(new EntryKeys("other:thing", List.of()))).source();

        assertTrue(source.contains("public static final Key OTHER_THING = Key.key(\"other\", \"thing\");"),
                "key of a foreign namespace:\n" + source);
    }

    @Test
    void aliasIsDeprecatedForRemovalAndRenamedToCurrentConstant() {
        String source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS,
                List.of(new EntryKeys("cygnus:iron_sword", List.of("cygnus:old_sword")))).source();

        assertTrue(source.matches("(?s).*@Deprecated\\(\\s*forRemoval = true\\s*\\).*"), "alias must be deprecated for removal:\n" + source);
        assertTrue(source.contains("public static final Key OLD_SWORD = Key.key(\"cygnus\", \"old_sword\");"),
                "alias key:\n" + source);
        assertTrue(source.contains("Renamed to {@link #IRON_SWORD}."), "alias javadoc:\n" + source);
    }

    @Test
    void emptyTypeDeclaresClassWithoutConstants() {
        String source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.SOUNDS, List.of()).source();

        assertTrue(source.contains("public final class CygnusSoundKeys {"), "class of an empty type:\n" + source);
        assertFalse(source.contains("public static final Key"), "no constants for an empty type:\n" + source);
    }

    @Test
    void privateConstructorPreventsInstances() {
        String source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS, List.of()).source();

        assertTrue(source.contains("private CygnusItemKeys() {"), "private constructor:\n" + source);
    }

    @Test
    void javadocNamesProjectAndVersionWithoutTimestamp() {
        String source = KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS, List.of()).source();

        assertTrue(source.contains("Generated by the Vulpes Gradle plugin from {@code cygnus} 1.4.0, do not edit."),
                "provenance line:\n" + source);
        assertFalse(source.contains("2026"), "no timestamp in generated source:\n" + source);
    }

    @Test
    void collidingKeysFailNamingBoth() {
        CodegenException exception = assertThrows(CodegenException.class,
                () -> KeysGenerator.generate(TestContents.CONTEXT, EntityType.ITEMS, List.of(
                        new EntryKeys("cygnus:iron-sword", List.of()), new EntryKeys("cygnus:iron_sword", List.of()))),
                "colliding keys must fail");

        assertTrue(exception.getMessage().contains("cygnus:iron-sword") && exception.getMessage().contains("cygnus:iron_sword"),
                "message must name both keys: " + exception.getMessage());
    }
}
